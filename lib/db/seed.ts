function makeProject({
  id,
  reference,
  title,
  brief,
  designDirection,
  status,
  review,
  reviewerName,
  reviewNotes,
  createdAt,
  updatedAt,
}: {
  id: string;
  reference: string;
  title: string;
  brief: StudioBrief;
  designDirection: ContentProject["designDirection"];
  status: ContentProject["status"];
  review: ReviewChecklist;
  reviewerName: string;
  reviewNotes: string;
  createdAt: string;
  updatedAt: string;
}): ContentProject {
  const research = generateResearch(brief);
  const outline = generateOutline(brief, research);
  const slides = generateSlides(brief, outline);
  return {
    id,
    reference,
    title,
    brief,
    research: { ...research, generatedAt: createdAt },
    outline,
    slides,
    designDirection,
    review,
    reviewerName,
    reviewNotes,
    status,
    source: "seed",
    isSample: true,
    createdAt,
    updatedAt,
  };
}

