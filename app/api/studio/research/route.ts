import { NextResponse } from "next/server";
import { researchRequestSchema, researchDeckSchema } from "@/lib/validation/schemas";
import { generateResearch } from "@/lib/studio/generator";
import { hasN8nContent, getN8nWebhookSecret } from "@/lib/config";
import { getClientIdentifier } from "@/lib/request";
import { rateLimit, rateLimitKey } from "@/lib/rate-limit";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

export async function POST(request: Request) {
  const identifier = await getClientIdentifier();
  const limit = rateLimit(rateLimitKey("studio-research", identifier), 20, 10 * 60_000);
  if (!limit.ok) {
    return NextResponse.json(
      { error: "Too many research requests. Please slow down." },
      {
        status: 429,
        headers: { "Retry-After": String(limit.retryAfterSeconds) },
      },
    );
  }

  const length = Number(request.headers.get("content-length") ?? "0");
  if (length > 12_000) {
    return NextResponse.json({ error: "Request too large." }, { status: 413 });
  }

  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON body." }, { status: 400 });
  }

  const parsed = researchRequestSchema.safeParse(body);
  if (!parsed.success) {
    return NextResponse.json(
      {
        error: "Check the creative brief.",
        fields: parsed.error.flatten().fieldErrors,
      },
      { status: 422 },
    );
  }

  const brief = parsed.data;
  const fallback = (warning?: string) => {
    const deck = generateResearch(brief);
    return NextResponse.json({
      ...deck,
      engine: "local-demo",
      warning:
        warning ??
        "Generated by the local deterministic demo engine. No external model was called.",
      generatedAt: new Date().toISOString(),
    });
  };

  if (!hasN8nContent()) {
    return fallback();
  }

  try {
    const webhook = process.env.N8N_CONTENT_WEBHOOK_URL;
    if (!webhook) return fallback();
    const secret = getN8nWebhookSecret();
    const response = await fetch(webhook, {
      method: "POST",
      headers: {
        "content-type": "application/json",
        ...(secret ? { "x-pfa-webhook-secret": secret } : {}),
      },
      body: JSON.stringify({
        action: "research",
        brief,
        requestedAt: new Date().toISOString(),
      }),
      signal: AbortSignal.timeout(15_000),
      cache: "no-store",
    });

    if (!response.ok) {
      return fallback(
        "The configured n8n workflow did not respond successfully. A local demo research deck was generated instead.",
      );
    }

    const payload: unknown = await response.json();
    const validated = researchDeckSchema.safeParse({
      ...(typeof payload === "object" && payload !== null ? payload : {}),
      engine: "n8n",
    });

    if (!validated.success) {
      return fallback(
        "The n8n response did not match the expected research contract. A local demo deck was used instead.",
      );
    }

    return NextResponse.json({
      ...validated.data,
      engine: "n8n",
      generatedAt: validated.data.generatedAt ?? new Date().toISOString(),
    });
  } catch {
    return fallback(
      "The configured n8n workflow was unreachable. A local demo research deck was generated instead.",
    );
  }
}

export async function GET() {
  return NextResponse.json(
    {
      error: "Use POST to request a research deck.",
      mode: hasN8nContent() ? "n8n-configured" : "local-demo",
    },
    { status: 405, headers: { Allow: "POST" } },
  );
}
